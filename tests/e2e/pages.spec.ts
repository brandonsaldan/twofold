import { expect, test } from '@playwright/test'

test('a SNP page shows genotypes, credit and a way back to the app', async ({ page }) => {
  await page.goto('/snps/rs1801133/')
  await expect(page).toHaveTitle('rs1801133 (MTHFR): what GG, AG and AA mean | Twofold')
  await expect(page.getByRole('heading', { level: 1, name: 'rs1801133' })).toBeVisible()
  const top = page.locator('.geno-card.is-top')
  await expect(top.locator('.geno-card-letters')).toHaveText('A;A')
  await expect(top.locator('a')).toHaveAttribute('href', '/snps/rs1801133/aa/')
  await expect(page.getByRole('link', { name: '(T;T)' })).toHaveAttribute('href', 'https://www.snpedia.com/index.php/rs1801133(T;T)')
  await expect(page.getByRole('navigation', { name: 'Breadcrumb' }).getByRole('link', { name: 'MTHFR' })).toHaveAttribute('href', '/genes/mthfr/')
  const breadcrumbs = JSON.parse(await page.locator('script[type="application/ld+json"]').textContent() || '{}')
  expect(breadcrumbs['@type']).toBe('BreadcrumbList')
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'https://twofold.brandonsaldan.com/snps/rs1801133/')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', /^index, follow/)
  await expect(page.getByRole('link', { name: 'CC BY-NC-SA 3.0 US' }).first()).toBeVisible()
  await expect(page.getByText('SNPedia is a community-edited wiki.')).toBeVisible()
  await page.getByRole('link', { name: 'All MTHFR SNPs' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'MTHFR' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'rs1801131', exact: true })).toHaveAttribute('href', '/snps/rs1801131/')
  await page.getByRole('link', { name: 'Check your own file' }).click()
  await expect(page.locator('.hero').getByRole('button', { name: 'Try a sample report' })).toBeVisible()
})

test('thin SNP pages stay reachable but are not indexed', async ({ page, request }) => {
  await page.goto('/snps/rs80356504/')
  await expect(page.locator('meta[name="robots"]')).toHaveAttribute('content', 'noindex, follow')
  const sitemap = await (await request.get('/sitemaps/snps.xml')).text()
  expect(sitemap).not.toContain('/snps/rs80356504/')
})

test('explore search suggests topics and opens SNPs', async ({ page }) => {
  await page.goto('/about/')
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Explore' }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Explore' })).toBeVisible()
  const search = page.getByRole('combobox')
  await search.fill('warf')
  await expect(page.getByRole('option', { name: /Warfarin/ })).toBeVisible()
  await search.press('Enter')
  await expect(page).toHaveURL(/\/medicines\/warfarin\/$/)
  await page.goto('/explore/')
  await page.getByRole('combobox').fill('RS1801133')
  await page.getByRole('combobox').press('Enter')
  await expect(page).toHaveURL(/\/snps\/rs1801133\/$/)
  await page.goto('/explore/')
  await page.getByRole('combobox').fill('rs1')
  await page.getByRole('button', { name: 'Search' }).click()
  await expect(page.getByRole('link', { name: 'Open rs1 on SNPedia' })).toBeVisible()
})

