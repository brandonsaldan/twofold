test('genotype pages and listing pages link together', async ({ page, request }) => {
  await page.goto('/genes/')
  await page.getByPlaceholder('Filter genes').fill('mthfr')
  await expect(page.locator('#index [data-item]:not([hidden])')).toHaveCount(1)
  await page.getByRole('link', { name: /^MTHFR/ }).click()
  await page.getByRole('link', { name: /^A;A/ }).first().click()
  await expect(page).toHaveURL(/\/snps\/rs1801133\/aa\/$/)
  await expect(page.getByRole('heading', { level: 1, name: 'rs1801133(A;A)' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Other genotypes of rs1801133' })).toBeVisible()
  await expect(page.locator('.geno-card a').first()).toHaveAttribute('href', '/snps/rs1801133/gg/')
  await expect(page.getByRole('link', { name: 'rs1801133(T;T)', exact: true })).toHaveAttribute('href', 'https://www.snpedia.com/index.php/rs1801133(T;T)')
  await expect(page.getByRole('navigation', { name: 'Breadcrumb' }).getByRole('link', { name: 'rs1801133' })).toHaveAttribute('href', '/snps/rs1801133/')
  expect(await (await request.get('/sitemaps/genotypes.xml')).text()).toContain('<loc>https://twofold.brandonsaldan.com/snps/rs1801133/aa/</loc>')
  expect(await (await request.get('/sitemaps/pages.xml')).text()).toContain('<loc>https://twofold.brandonsaldan.com/conditions/</loc>')
})

test('the sitemap lists the indexed pages and the service worker skips them', async ({ request }) => {
  const index = await (await request.get('/sitemap.xml')).text()
  for (const name of ['pages', 'topics', 'snps', 'genotypes']) expect(index).toContain(`<loc>https://twofold.brandonsaldan.com/sitemaps/${name}.xml</loc>`)
  expect(await (await request.get('/sitemaps/snps.xml')).text()).toContain('<loc>https://twofold.brandonsaldan.com/snps/rs1801133/</loc>')
  expect(await (await request.get('/sitemaps/topics.xml')).text()).toContain('<loc>https://twofold.brandonsaldan.com/genes/mthfr/</loc>')
  const pages = await (await request.get('/sitemaps/pages.xml')).text()
  expect(pages).toContain('<loc>https://twofold.brandonsaldan.com/explore/</loc>')
  expect(pages).toContain('<loc>https://twofold.brandonsaldan.com/promethease-alternative/</loc>')
  expect(await (await request.get('/robots.txt')).text()).toContain('Disallow: /data/')
  const worker = await (await request.get('/sw.js')).text()
  expect(worker).toContain('"/data/core.json"')
  for (const path of ['/snps/', '/genes/', '/conditions/', '/medicines/', '/explore/', '/data/search.json']) expect(worker).not.toContain(path)
})

test('report filters use the custom dropdown with keyboard support', async ({ page }) => {
  await page.goto('/', { waitUntil: 'networkidle' })
  await page.locator('.hero').getByRole('button', { name: 'Try a sample report' }).click()
  await page.getByRole('button', { name: 'I understand, open the report' }).click()
  await page.getByRole('navigation', { name: 'Report sections' }).getByRole('button', { name: /^Findings/ }).click()
  const sort = page.getByRole('button', { name: /^Sort/ })
  await sort.click()
  await page.getByRole('option', { name: 'rsID' }).click()
  await expect(sort).toContainText('rsID')
  await sort.press('ArrowDown')
  await expect(page.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  await expect(sort).toContainText('Magnitude')
  await expect(page.getByRole('listbox')).toHaveCount(0)
})

